"""Regression checks for artifact bytes, post-freeze chronology and release integrity."""
import pytest

from redesign.pipeline import phase9_closeout as closeout
from test_pilot_evaluation import row


def test_csv_verification_preserves_crlf(tmp_path):
    content='observation,decision\r\na,not_vulnerable\r\n'
    path=tmp_path/'observations.csv';path.write_bytes(content.encode())
    assert path.read_text()!=content  # The original checker's failure mode.
    closeout.check_bytes(tmp_path,{'observations.csv':content})
    path.write_bytes(content.replace('a,','b,').encode())
    with pytest.raises(ValueError,match='Regenerated bytes differ'):
        closeout.check_bytes(tmp_path,{'observations.csv':content})


def test_chronology_rejects_prefreeze_or_reordered_dispatches():
    freeze='2026-10-21T03:00:00+00:00'
    valid=['2026-10-21T03:01:00+00:00','2026-10-21T03:02:00+00:00']
    assert closeout.chronology(valid,freeze)['after_freeze']
    with pytest.raises(ValueError,match='predates'):closeout.chronology([freeze],valid[0])
    with pytest.raises(ValueError,match='schedule'):closeout.chronology(list(reversed(valid)),freeze)


def test_independent_partition_keeps_wrong_cwe_abstentions_and_failures():
    rows=[row('a'),row('b',truth='vulnerable_CWE-121',llm='vulnerable_CWE-122'),
          row('c',llm='uncertain'),row('d',llm=None),
          row('e',shared_availability='context_unavailable'),row('f',truth='unresolved')]
    assert closeout.partition(rows,'llm')=={'A':5,'C':1,'E':1,'U':1,'M':2}


def test_results_release_round_trip_and_tampering(tmp_path,monkeypatch):
    root=tmp_path/'campaign';(root/'release').mkdir(parents=True)
    (root/'release/freeze.json').write_text('{}')
    (root/'attempt.json').write_text('{"raw":"preserved"}')
    monkeypatch.setattr(closeout,'verify_campaign',lambda root:None)
    result=closeout.package(root)
    assert result['status']=='phase9_complete'
    assert closeout.verify_package(root)['files']==2
    (root/'attempt.json').write_text('{"raw":"changed"}')
    with pytest.raises(ValueError,match='Locked artifact changed'):closeout.verify_package(root)
