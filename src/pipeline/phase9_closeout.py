def check_bytes(directory, files):
    for name, content in files.items():
        expected = content.encode('utf-8') if isinstance(content, str) else content
        require((directory/name).read_bytes() == expected, f'Regenerated bytes differ: {name}')


def partition(rows, method):
    """Independent integer count check, without evaluator/vectorized arithmetic."""
    counts = dict.fromkeys(('A','C','E','U','M'), 0)
    labels = {'not_vulnerable','vulnerable_CWE-121','vulnerable_CWE-122'}
    for row in rows:
        truth = row['binary_label']
        if truth not in labels: continue
        counts['A'] += 1
        prediction = row['predictions'][method]
        if row['shared_availability'] != 'available' or prediction['status'] not in ('classified','abstained'):
            outcome = 'M'
        elif prediction['decision'] not in labels: outcome = 'U'
        else: outcome = 'C' if prediction['decision']==truth else 'E'
        counts[outcome] += 1
    require(counts['A']==sum(counts[k] for k in ('C','E','U','M')), 'Outcome partition differs')
    return counts


def chronology(times, frozen_at):
    values = [datetime.fromisoformat(value) for value in times]
    start = datetime.fromisoformat(frozen_at)
    require(all(value >= start for value in values), 'Dispatch predates input freeze')
    require(values == sorted(values), 'Dispatch timestamps violate the frozen schedule')
    return {'first_dispatch':times[0] if times else None, 'last_dispatch':times[-1] if times else None,
            'after_freeze':True, 'schedule_order_preserved':True}


def audit(root, directory, results, report):
    manifest, _ = final_run.validate_manifest(directory, root)
    claim = read_json(root/'provenance/phase9-execution.json')
    require(claim == {'freeze_sha256':digest(root/'release/freeze.json'),
                     'run_manifest_sha256':digest(directory/'manifest.json')}, 'Execution claim differs')
    expected_slots = {run_llm.slot_name(s) for s in manifest['slots']}
    require({p.name for p in (directory/'slots').iterdir()}==expected_slots, 'Unexpected/missing slot directory')
    require({p.name for p in (directory/'baseline').iterdir()}==set(manifest['inputs']), 'Unexpected/missing baseline job')
    frozen_at = read_json(root/'release/freeze.json')['created_at_utc']
    grouped = {}; failures = []; times = []; sessions = Counter()
    by_id = {r['observation_id']:r for r in report['rows']}
    for slot in manifest['slots']:
        name = run_llm.slot_name(slot); path = directory/'slots'/name
        result = run_llm.result_for(directory, slot, manifest)
        dispatch = read_json(path/'dispatch.json')
        times.append(dispatch['started_at']); sessions[dispatch['server_sha256']] += 1
        grouped.setdefault(slot['observation_id'], []).append(result)
        if result['status'] != 'valid':
            failures.append({'slot':name,'status':result['status'],'error':result.get('error'),
                             'raw_response_retained':result.get('response_body') is not None})
    for identifier, attempts in grouped.items():
        votes = Counter(a['parsed']['decision'] for a in attempts if a['status']=='valid')
        winners = [label for label,n in votes.items() if n>=2]
        decision = winners[0] if winners else 'uncertain' if votes else None
        actual = by_id[identifier]['predictions']['llm']
        require(len(attempts)==3 and decision==actual['decision'] and dict(votes)==actual['votes'],
                'Independent majority-vote check differs')
    independent = {m:partition(report['rows'],m) for m in ('baseline','llm')}
    for method, counts in independent.items():
        require(all(v==report['primary'][method][k]['estimate'] for k,v in counts.items()), 'Independent count check differs')
    base_times = [read_json(directory/'baseline'/identifier/'dispatch.json')['started_at'] for identifier in manifest['inputs']]
    # Baseline insertion order is the frozen observation order, independent of
    # the LLM's SHA-sorted repetition schedule.
    baseline_chronology = chronology(base_times, frozen_at)
    failures_by_kind = Counter()
    for failure in failures:
        error = failure['error'] or ''
        kind = ('evidence_outside_bundle' if 'outside bundle' in error else
                'duplicate_evidence' if 'non-unique elements' in error else failure['status'])
        failures_by_kind[kind] += 1
    hashes = {name:digest(results/name) for name in final_analysis.artifacts(report)}
    return {'schema_version':1,'status':'verified_complete','campaign_id':read_json(root/'release/freeze.json')['freeze_id'],
        'planned_observations':len(report['rows']),'scheduled_slots':len(manifest['slots']),
        'pending_slots':0,'baseline_replay':'all completed predictions regenerate from saved IR',
        'independent_exact_label_counts':independent,'independent_vote_check':'passed',
        'llm_chronology':chronology(times,frozen_at),'baseline_chronology':baseline_chronology,
        'runtime_session_dispatches':dict(sessions),'failures':failures,'failure_causes':dict(failures_by_kind),
        'core_artifact_sha256':hashes,'closeout_method_sha256':digest(Path(__file__)),
        'verification_amendment':{'scope':'Post-run artifact comparison only; no predictor, input, score, or result changes',
            'original_checker_issue':'final_analysis --check uses read_text(), normalizing CSV CRLF to LF before comparing with unnormalized csv.DictWriter output',
            'replacement':'Regenerate with unchanged final_analysis.artifacts and compare UTF-8 bytes for every core artifact'},
        'timing_limit':'Saved LLM elapsed seconds exclude the two interrupted requests and inter-session idle time.'}


def csv_text(fields, rows):
    import csv
    stream = io.StringIO(newline='')
    writer = csv.DictWriter(stream, fieldnames=fields, lineterminator='\n')
    writer.writeheader(); writer.writerows(rows)
    return stream.getvalue()


def supplemental(report, validation):
    metrics = []
    for scope, groups in [('primary',{'all':report['primary']}), *report['subgroups'].items()]:
        for group, values in groups.items():
            for method in ('baseline','llm'):
                for metric in ('A','C','E','U','M','correct_rate','coverage','selective_accuracy','recall','false_positive_rate'):
                    value = values[method][metric]
                    metrics.append({'scope':scope,'group':group,'method':method,'metric':metric,
                                    'estimate':value['estimate'],**value['interval']})
    dispositions = []
    for row in report['disposition_by_optimization_cwe']:
        dispositions.append({**{k:row[k] for k in ('optimization','cwe','planned','unresolved_truth','extraction_failures','context_failures')},
            **{k:row['operations'].get(k,0) for k in ('present','inlined/merged','eliminated')},
            **{k:row['binary_classes'].get(k,0) for k in ('not_vulnerable','vulnerable_CWE-121','vulnerable_CWE-122')},
            **{method+'_'+k:v for method,counts in row['methods'].items() for k,v in counts.items()}})
    contrasts = []
    for name, value in {**report['matched_contrasts'],**{f'stripped_minus_retained_{k}':v for k,v in report['symbol_contrasts_by_level'].items()}}.items():
        for method, prediction in value['methods'].items():
            contrasts.append({'contrast':name,'method':method,'matched_cells':value['matched_cells'],'families':value['families'],
                'estimate':prediction['second_minus_first_correct_rate'],**prediction['interval']})
    files = {'validation.json':canonical(validation)}
    for name, rows in (('metrics.csv',metrics),('dispositions.csv',dispositions),('contrasts.csv',contrasts)):
        files[name] = csv_text(list(rows[0]),rows)
    return files


def figure(report):
    import matplotlib
    matplotlib.use('Agg')
    from matplotlib import pyplot as plt
    import numpy as np
    with plt.rc_context({'font.family':'DejaVu Sans','svg.hashsalt':'juliet-phase9-v1'}):
        fig, axes = plt.subplots(1,2,figsize=(10,4),layout='constrained')
        for index,method in enumerate(('baseline','llm')):
            value = report['primary'][method]['correct_rate']
            estimate = value['estimate']*100
            axes[0].bar(index,estimate,color=('#64748b','#2563eb')[index])
            axes[0].errorbar(index,estimate,yerr=[[estimate-value['interval']['lower']*100],
                [value['interval']['upper']*100-estimate]],color='black',capsize=5)
            axes[0].text(index,estimate+3,f'{estimate:.1f}%',ha='center')
            rates = [report['subgroups']['optimization'][opt][method]['correct_rate']['estimate']*100 for opt in ('O0','O1','O2','O3')]
            axes[1].plot(np.arange(4),rates,marker='o',label=method)
        axes[0].set_xticks([0,1],['Baseline','LLM']);axes[0].set_title('Exact-label correct rate, all 160 cells')
        axes[1].set_xticks(range(4),['O0','O1','O2','O3']);axes[1].set_title('Correct rate by optimization, 40 cells each');axes[1].legend()
        for axis in axes:
            axis.set_ylim(0,105);axis.set_ylabel('Correct / adjudicated cells (%)')
        fig.suptitle('Ten source families; family-cluster intervals are exploratory',fontsize=11)
        outputs = {}
        for extension in ('png','svg'):
            stream = io.BytesIO()
            metadata = {'Date':None} if extension=='svg' else {'Software':'phase9_closeout'}
            fig.savefig(stream,format=extension,dpi=160,metadata=metadata)
            outputs['correct_rate.'+extension]=stream.getvalue()
        plt.close(fig)
        return outputs


def closeout(root, directory, results, check=False):
    report = final_analysis.analyze(directory, root)
    check_bytes(results,final_analysis.artifacts(report))
    validation = audit(root,directory,results,report)
    files = {**supplemental(report,validation),**figure(report)}
    target = results/'closeout'
    if check: check_bytes(target,files)
    else:
        target.mkdir(parents=True,exist_ok=False)
        for name, value in files.items():
            with (target/name).open('xb') as stream:
                stream.write(value.encode('utf-8') if isinstance(value,str) else value)
    return validation


def package(root):
    """Bind the full campaign, attempts, IR, analysis and closeout snapshots."""
    verify_campaign(root)
    exclude = {'release/phase9-results.json','release/phase9-results.tar.gz'}
    files = {p.relative_to(root).as_posix():digest(p) for p in sorted(root.rglob('*'))
             if p.is_file() and p.relative_to(root).as_posix() not in exclude
             and p.name not in ('runner.lock','baseline.lock') and not p.name.startswith('.pending-')}
    path = root/'release/phase9-results.tar.gz'
    with path.open('xb') as stream:
        with gzip.GzipFile(filename='',fileobj=stream,mode='wb',mtime=0) as compressed:
            with tarfile.open(fileobj=compressed,mode='w') as archive:
                for name in files:
                    content=(root/name).read_bytes()
                    item=tarfile.TarInfo(name);item.size=len(content);item.mode=(root/name).stat().st_mode&0o777
                    archive.addfile(item,io.BytesIO(content))
    manifest = {'schema_version':1,'status':'phase9_complete','archive':path.relative_to(root).as_posix(),
        'archive_sha256':digest(path),'files':files,'private_evidence_included':True,
        'input_freeze_sha256':digest(root/'release/freeze.json'),'closeout_method_sha256':digest(Path(__file__)),
        'replay_dependencies':'Original final-v1 release, same repository methods and pinned external toolchain; no live model server needed.'}
    llm_runtime.write_new(root/'release/phase9-results.json',manifest)
    verify_package(root)
    path.chmod(0o444);(root/'release/phase9-results.json').chmod(0o444)
    return {'status':manifest['status'],'files':len(files),'archive_sha256':manifest['archive_sha256']}


def verify_package(root):
    from .final_freeze import verify_archive
    manifest=read_json(root/'release/phase9-results.json')
    require(manifest['status']=='phase9_complete' and
            manifest['input_freeze_sha256']==digest(root/'release/freeze.json'), 'Results release identity differs')
    method_lock.check_files(manifest['files'],root)
    require(digest(root/manifest['archive'])==manifest['archive_sha256'],'Results archive changed')
    verify_archive(root/manifest['archive'],manifest['files'])
    return {'status':'verified','files':len(manifest['files']),'archive_sha256':manifest['archive_sha256']}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action',choices=('generate','check','package','verify-package'))
    parser.add_argument('--root',type=Path,default=AMENDED)
    args=parser.parse_args();root=args.root.resolve()
    if args.action=='package':
        closeout(root,root/'build/final/llm-runs/phase9-a',root/'results/final/phase9-a',check=True)
        result=package(root)
    elif args.action=='verify-package':result=verify_package(root)
    else:
        result=closeout(root,root/'build/final/llm-runs/phase9-a',root/'results/final/phase9-a',check=args.action=='check')
        result={k:v for k,v in result.items() if k in ('status','planned_observations','scheduled_slots','independent_exact_label_counts')}
    print(canonical(result))


if __name__=='__main__':main()
